// Helper utilities
export function getAllProducts(): Product[] {
  return products;
}

export function getProductBySlug(slug: string): Product | undefined {
  return products.find((p) => p.slug === slug);
}

export function getProductsByBrand(brand: StoreBrand): Product[] {
  return products.filter((p) => p.brand === brand);
}

export function getFeaturedProducts(brand?: StoreBrand): Product[] {
  if (brand) {
    return products.filter((p) => p.brand === brand && p.featured);
  }
  return products.filter((p) => p.featured);
}

export function getSeasonalProducts(): Product[] {
  return products.filter((p) => p.seasonal);
}

export function getRelatedProducts(product: Product, limit = 4): Product[] {
  return products
    .filter((p) => p.id !== product.id && (p.brand === product.brand || p.categoryId === product.categoryId))
    .slice(0, limit);
}

export function searchProducts(query: string, brand?: StoreBrand): Product[] {
  const cleanQ = query.trim().toLowerCase();
  if (!cleanQ) {
    return brand ? getProductsByBrand(brand) : getAllProducts();
  }
  return products.filter((p) => {
    const matchesBrand = brand ? p.brand === brand : true;
    const matchesQuery =
      p.nameBn.toLowerCase().includes(cleanQ) ||
      p.nameEn.toLowerCase().includes(cleanQ) ||
      p.categoryBn.toLowerCase().includes(cleanQ) ||
      p.categoryEn.toLowerCase().includes(cleanQ) ||
      p.subtitleBn.toLowerCase().includes(cleanQ) ||
      p.subtitleEn.toLowerCase().includes(cleanQ);
    return matchesBrand && matchesQuery;
  });
}
